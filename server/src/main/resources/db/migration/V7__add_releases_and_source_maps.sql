CREATE TABLE releases (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    application_id BIGINT UNSIGNED NOT NULL,
    release_name VARCHAR(100) COLLATE utf8mb4_0900_bin NOT NULL,
    commit_sha VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    manifest JSON NOT NULL,
    artifact_count INT UNSIGNED NOT NULL DEFAULT 0,
    total_map_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at BIGINT NOT NULL,
    finalized_at BIGINT NULL,
    deployed_at BIGINT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_releases_app_name UNIQUE (application_id, release_name),
    CONSTRAINT fk_releases_application FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE,
    CONSTRAINT fk_releases_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_releases_status CHECK (status IN ('draft', 'finalized')),
    CONSTRAINT chk_releases_time CHECK (created_at >= 0 AND (finalized_at IS NULL OR finalized_at >= 0) AND (deployed_at IS NULL OR deployed_at >= 0)),
    CONSTRAINT chk_releases_manifest CHECK (JSON_TYPE(manifest) = 'ARRAY' AND JSON_LENGTH(manifest) BETWEEN 1 AND 100),
    INDEX idx_releases_app_created (application_id, created_at DESC, id DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE source_maps (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    release_id BIGINT UNSIGNED NOT NULL,
    artifact_path VARCHAR(1024) COLLATE utf8mb4_0900_bin NOT NULL,
    artifact_path_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    js_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    map_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    js_bytes BIGINT UNSIGNED NOT NULL,
    map_bytes BIGINT UNSIGNED NOT NULL,
    map_content MEDIUMBLOB NOT NULL,
    source_count INT UNSIGNED NOT NULL,
    sources_with_content INT UNSIGNED NOT NULL,
    uploaded_by BIGINT UNSIGNED NOT NULL,
    uploaded_at BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_source_maps_release_path UNIQUE (release_id, artifact_path_hash),
    CONSTRAINT fk_source_maps_release FOREIGN KEY (release_id) REFERENCES releases (id) ON DELETE CASCADE,
    CONSTRAINT fk_source_maps_uploader FOREIGN KEY (uploaded_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_source_maps_size CHECK (js_bytes > 0 AND map_bytes > 0 AND map_bytes = OCTET_LENGTH(map_content)),
    CONSTRAINT chk_source_maps_sources CHECK (sources_with_content <= source_count),
    CONSTRAINT chk_source_maps_time CHECK (uploaded_at >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
